constexpr uint8_t ROUND_CONSTANTS[ROUND_COUNT] = {
    0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36,
};

static void add_round_key(uint8_t state[static SPEC_3DS_AES_BLOCK_SIZE], const uint8_t *round_key) {
    for (size_t index = 0; index < SPEC_3DS_AES_BLOCK_SIZE; ++index) {
        state[index] ^= round_key[index];
    }
}

static void substitute_bytes(uint8_t state[static SPEC_3DS_AES_BLOCK_SIZE]) {
    for (size_t index = 0; index < SPEC_3DS_AES_BLOCK_SIZE; ++index) {
        state[index] = SUBSTITUTIONS[state[index]];
    }
}

// The state is column by column, so row r of column c is state[c * 4 + r].
static void shift_rows(uint8_t state[static SPEC_3DS_AES_BLOCK_SIZE]) {
    uint8_t shifted[SPEC_3DS_AES_BLOCK_SIZE];
    for (size_t column = 0; column < 4; ++column) {
        for (size_t row = 0; row < 4; ++row) {
            shifted[column * 4 + row] = state[((column + row) % 4) * 4 + row];
        }
    }
    memcpy(state, shifted, sizeof shifted);
}

// Multiplication by x in GF(2^8).
static uint8_t times_two(uint8_t byte) {
    uint8_t doubled = (uint8_t)(byte << 1);
    return (byte & 0x80) != 0 ? (uint8_t)(doubled ^ REDUCING_POLYNOMIAL) : doubled;
}

static void mix_columns(uint8_t state[static SPEC_3DS_AES_BLOCK_SIZE]) {
    for (size_t column = 0; column < 4; ++column) {
        uint8_t *bytes = &state[column * 4];
        uint8_t all = (uint8_t)(bytes[0] ^ bytes[1] ^ bytes[2] ^ bytes[3]);
        uint8_t first = bytes[0];
        for (size_t row = 0; row < 4; ++row) {
            uint8_t next = row == 3 ? first : bytes[row + 1];
            bytes[row] ^= (uint8_t)(all ^ times_two((uint8_t)(bytes[row] ^ next)));
        }
    }
}

void spec_3ds_aes128_encrypt(uint8_t block[static SPEC_3DS_AES_BLOCK_SIZE],
                             const uint8_t round_keys[static SPEC_3DS_AES_ROUND_KEYS_SIZE]) {
    add_round_key(block, round_keys);
    for (size_t round = 1; round <= ROUND_COUNT; ++round) {
        substitute_bytes(block);
        shift_rows(block);
        if (round != ROUND_COUNT) {
            mix_columns(block);
        }
        add_round_key(block, &round_keys[round * SPEC_3DS_AES_BLOCK_SIZE]);
    }
}

void spec_3ds_aes128_expand_key(uint8_t round_keys[static SPEC_3DS_AES_ROUND_KEYS_SIZE],
                                const uint8_t key[static SPEC_3DS_AES_BLOCK_SIZE]) {
    memcpy(round_keys, key, SPEC_3DS_AES_BLOCK_SIZE);
    size_t word_count = SPEC_3DS_AES_ROUND_KEYS_SIZE / WORD_SIZE;
    for (size_t word = KEY_WORD_COUNT; word < word_count; ++word) {
        uint8_t temporary[WORD_SIZE];
        memcpy(temporary, &round_keys[(word - 1) * WORD_SIZE], WORD_SIZE);
        if (word % KEY_WORD_COUNT == 0) {
            uint8_t first = temporary[0];
            temporary[0] =
                (uint8_t)(SUBSTITUTIONS[temporary[1]] ^ ROUND_CONSTANTS[word / KEY_WORD_COUNT - 1]);
            temporary[1] = SUBSTITUTIONS[temporary[2]];
            temporary[2] = SUBSTITUTIONS[temporary[3]];
            temporary[3] = SUBSTITUTIONS[first];
        }
        for (size_t index = 0; index < WORD_SIZE; ++index) {
            round_keys[word * WORD_SIZE + index] =
                (uint8_t)(round_keys[(word - KEY_WORD_COUNT) * WORD_SIZE + index]
                          ^ temporary[index]);
        }
    }
}
